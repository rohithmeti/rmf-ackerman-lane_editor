#!/usr/bin/env python3
"""Put the AprilTags of a graph into a Gazebo world - at exactly the coordinates the graph was designed with.

  python3 export_gazebo.py my_layout.taggraph.json --world-in my_world.sdf [--out-dir out] [--ros2-agv ~/ros2_agv]

Input : <name>.taggraph.json written by the AprilTag Graph Maker (tag ids, map-frame AND simulator-frame coordinates, lanes)
        --world-in  the Gazebo world (.sdf) that the tags go into (unchanged otherwise)
Output (in --out-dir):
  worlds/warehouse_<name>.sdf           the world with one flat tag model per node at its world coordinates
  config/tag_map_warehouse_<name>.yaml  id -> world (x, y, yaw) and the lanes: the table the navigation stack loads
  worlds/warehouse_<name>.spawn.yaml    start pose of the robot: on tag <start_tag>, facing along a lane
  models/agv_tags/...                   textures (tag36h11, one PNG per id) + the model folder the world refers to
  tags_sheet.pdf                        printable tags with id and coordinates (contact sheet; --full-size = real size, A3, one per page)
--ros2-agv <workspace>: also copies these into the ros2_agv workspace so that
  ros2 launch agv_tag_nav agv01_navigation.launch.py layout:=<name>     starts it (after colcon build).
Other worlds: add the printed models folder to IGN_GAZEBO_RESOURCE_PATH (textures are found through model://agv_tags/...).
"""
import argparse, json, math, os, re, shutil, sys
import numpy as np


def tag_png(tag_id, size_px=320, border_px=40):
    """tag36h11 image like the ones in the AprilTag PDF: 8x8 cells (black border included) + a white quiet zone; rotated 180 deg
    because that is the orientation convention of the simulator's tag models (tag 'up' = +y of the tag frame)."""
    import cv2
    d = cv2.aruco.Dictionary_get(cv2.aruco.DICT_APRILTAG_36h11)
    m = cv2.aruco.drawMarker(d, int(tag_id), size_px, borderBits=1)
    m = cv2.copyMakeBorder(m, border_px, border_px, border_px, border_px, cv2.BORDER_CONSTANT, value=255)
    return np.rot90(m, 2)


def yaml_tag_map(g, header):
    yaw = math.radians(g['frame_map_to_world']['yaw_deg'])
    s = ('# AprilTag graph in the SIMULATOR (world) frame: id -> (x, y, yaw); edge = lane. Generated by export_gazebo.py\n'
         f'# {header}\nfamily: tag36h11\ntag_size: {g["tag_size"]}\nframe: map\nnodes:\n')
    for n in g['nodes']:
        s += f"  {n['id']}: {{x: {n['world']['x']}, y: {n['world']['y']}, yaw: {round(n['yaw_world'], 4)}}}\n"
    s += 'edges:\n' + ''.join(f"- {{from: {e['from']}, to: {e['to']}, is_bidirectional: true}}\n" for e in g['edges'])
    return s


def start_pose(g):
    nodes = {n['id']: n for n in g['nodes']}
    tid = g.get('start_tag', 1)
    if tid not in nodes: tid = min(nodes)
    n = nodes[tid]; best = None
    for e in g['edges']:
        if tid in (e['from'], e['to']):
            o = nodes[e['to'] if e['from'] == tid else e['from']]
            dx, dy = o['world']['x'] - n['world']['x'], o['world']['y'] - n['world']['y']
            if best is None or dy > best[1] + 1e-6: best = (dx, dy)               # prefer driving "north"
    yaw = math.atan2(best[1], best[0]) if best else 0.0
    return tid, n['world']['x'], n['world']['y'], yaw


def sdf_block(g, tag_z):
    s = f'\n    <!-- ===== {len(g["nodes"])} AprilTag floor markers (export_gazebo.py) ===== -->\n'
    for n in g['nodes']:
        i = n['id']
        s += (f'    <model name="tag_{i}"><static>true</static><pose>{n["world"]["x"]:.3f} {n["world"]["y"]:.3f} {tag_z} 0 0 {n["yaw_world"]:.5f}</pose><link name="link">'
              f'<visual name="v"><pose>0 0 0.0015 0 0 3.14159265</pose><cast_shadows>false</cast_shadows><geometry><plane><normal>0 0 1</normal><size>0.25 0.25</size></plane></geometry>'
              f'<material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0 0 0 1</specular><pbr><metal>'
              f'<albedo_map>model://agv_tags/materials/textures/tag36_11_{i:05d}.png</albedo_map><roughness>1.0</roughness><metalness>0.0</metalness></metal></pbr></material></visual></link></model>\n')
    return s


def sheet_pdf(g, path, full_size):
    from PIL import Image, ImageDraw, ImageFont
    Image.init()                                                                  # registers the JPEG plugin the PDF writer needs
    try: font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 34); small = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 24)
    except Exception: font = small = ImageFont.load_default()
    dpi = 150; pages = []
    if full_size:                                                                 # A3 portrait, black square = tag_size, one tag per page
        W, H = int(11.69 * dpi), int(16.54 * dpi); full = g['tag_size'] * 10 / 8; px = int(full / 0.0254 * dpi)
        for n in g['nodes']:
            pg = Image.new('L', (W, H), 255); t = Image.fromarray(tag_png(n['id'], 320, 40)).resize((px, px), Image.NEAREST); pg.paste(t, ((W - px) // 2, int(H * 0.12)))
            d = ImageDraw.Draw(pg); d.text((W // 2, int(H * 0.12) + px + 60), f"tag {n['id']}", fill=0, font=font, anchor='mm')
            d.text((W // 2, int(H * 0.12) + px + 120), f"x {n['world']['x']:.2f} m   y {n['world']['y']:.2f} m   (simulator frame)", fill=0, font=small, anchor='mm')
            d.text((W // 2, int(H * 0.12) + px + 160), f"black square = {g['tag_size']*1000:.0f} mm, tag36h11", fill=90, font=small, anchor='mm'); pages.append(pg)
    else:                                                                         # A4 contact sheet 3 x 4, scaled (not real size)
        W, H = int(8.27 * dpi), int(11.69 * dpi); cols, rows = 3, 4; cw, ch = W // cols, H // rows; px = int(min(cw, ch) * 0.62)
        for k in range(0, len(g['nodes']), cols * rows):
            pg = Image.new('L', (W, H), 255); d = ImageDraw.Draw(pg)
            for j, n in enumerate(g['nodes'][k:k + cols * rows]):
                cx, cy = (j % cols) * cw + cw // 2, (j // cols) * ch + ch // 2
                pg.paste(Image.fromarray(tag_png(n['id'], 320, 40)).resize((px, px), Image.NEAREST), (cx - px // 2, cy - px // 2 - 20))
                d.text((cx, cy + px // 2 + 8), f"tag {n['id']}", fill=0, font=small, anchor='mm')
                d.text((cx, cy + px // 2 + 34), f"({n['world']['x']:.2f}, {n['world']['y']:.2f})", fill=90, font=small, anchor='mm')
            d.text((W // 2, H - 24), f"{g['name']}: tags {g['nodes'][k]['id']}..{g['nodes'][min(k + cols*rows, len(g['nodes'])) - 1]['id']}   (scaled, not real size: use --full-size)", fill=120, font=small, anchor='mm')
            pages.append(pg)
    pages[0].save(path, save_all=True, append_images=pages[1:], resolution=dpi, quality=95)
    return len(pages)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('graph'); ap.add_argument('--world-in', required=True)
    ap.add_argument('--out-dir', default=None); ap.add_argument('--ros2-agv', default=None, help='install into this ros2_agv workspace too')
    ap.add_argument('--tag-z', type=float, default=0.011, help='height of the floor surface in the world [m] (tags lie 1.5 mm above it)')
    ap.add_argument('--remove-model', action='append', default=[], metavar='NAME', help='remove an <include> with this <name> from the world (e.g. tugbot)')
    ap.add_argument('--full-size', action='store_true', help='printable sheet: real size, A3, one tag per page')
    ap.add_argument('--no-sheet', action='store_true')
    a = ap.parse_args()
    g = json.load(open(a.graph)); name = re.sub(r'[^\w]+', '_', g['name']); wname = f'warehouse_{name}'
    out = os.path.abspath(a.out_dir or f'gazebo_out_{name}'); tex = f'{out}/models/agv_tags/materials/textures'
    for d in ('worlds', 'config'): os.makedirs(f'{out}/{d}', exist_ok=True)
    os.makedirs(tex, exist_ok=True)
    if not g.get('frame_is_set'):
        print('NOTE: the simulator frame was not set in the GUI (dx = dy = yaw = 0): the tags are placed at the MAP coordinates.')

    import cv2
    for n in g['nodes']: cv2.imwrite(f"{tex}/tag36_11_{n['id']:05d}.png", tag_png(n['id']))
    open(f'{out}/models/agv_tags/model.config', 'w').write('<?xml version="1.0"?>\n<model><name>agv_tags</name><version>1.0</version><sdf version="1.8">model.sdf</sdf><description>AprilTag 36h11 floor textures</description></model>\n')
    open(f'{out}/models/agv_tags/model.sdf', 'w').write('<?xml version="1.0"?>\n<sdf version="1.8"><model name="agv_tags"><static>true</static><link name="link"/></model></sdf>\n')

    src = open(a.world_in).read()
    for m in a.remove_model:
        src, k = re.subn(r'\s*<include>(?:(?!</include>).)*?<name>\s*' + re.escape(m) + r'\s*</name>.*?</include>', '', src, flags=re.S)
        print(f'removed {k} <include> named "{m}"')
    if '<topic>/model/tugbot/cmd_vel</topic>' in src: src = src.replace('<topic>/model/tugbot/cmd_vel</topic>', '<topic>/cmd_vel_teleop</topic>')
    src = src.replace('<start_paused>true</start_paused>', '<start_paused>false</start_paused>')
    assert '</world>' in src, 'the input world has no </world>'
    open(f'{out}/worlds/{wname}.sdf', 'w').write(src.replace('  </world>', sdf_block(g, a.tag_z) + '  </world>', 1) if '  </world>' in src else src.replace('</world>', sdf_block(g, a.tag_z) + '</world>', 1))
    hdr = f"{g['name']}  frame map->world: dx {g['frame_map_to_world']['dx']:.3f} dy {g['frame_map_to_world']['dy']:.3f} yaw {g['frame_map_to_world']['yaw_deg']:.3f} deg"
    open(f'{out}/config/tag_map_{wname}.yaml', 'w').write(yaml_tag_map(g, hdr))
    tid, x, y, yaw = start_pose(g)
    open(f'{out}/worlds/{wname}.spawn.yaml', 'w').write(f'# robot start pose for {wname}.sdf: on tag {tid}, facing along a lane\nx: {x}\ny: {y}\nyaw: {yaw:.4f}\ntag: {tid}\n')
    pages = 0 if a.no_sheet else sheet_pdf(g, f'{out}/tags_sheet.pdf', a.full_size)
    print(f'{len(g["nodes"])} tags, {len(g["edges"])} lanes -> {out}\n  world   worlds/{wname}.sdf\n  tag map config/tag_map_{wname}.yaml\n  start   tag {tid} at ({x}, {y}) yaw {yaw:.3f}\n  sheet   {pages} page(s) tags_sheet.pdf')
    if a.ros2_agv:
        ws = os.path.expanduser(a.ros2_agv)
        for sub, files in (('src/my_bot_description/worlds', [f'worlds/{wname}.sdf', f'worlds/{wname}.spawn.yaml']), ('src/agv_tag_nav/config', [f'config/tag_map_{wname}.yaml'])):
            for f in files: shutil.copy(f'{out}/{f}', f'{ws}/{sub}/')
        shutil.copytree(f'{out}/models/agv_tags', f'{ws}/src/my_bot_description/models/agv_tags', dirs_exist_ok=True)
        print(f'installed into {ws}. Now:\n  cd {ws} && colcon build --symlink-install && source install/setup.bash\n  ros2 launch agv_tag_nav agv01_navigation.launch.py layout:={name}')
    else:
        print(f'To use another world: export IGN_GAZEBO_RESOURCE_PATH=$IGN_GAZEBO_RESOURCE_PATH:{out}/models:{out}/worlds ; gz sim {out}/worlds/{wname}.sdf')


if __name__ == '__main__':
    main()
